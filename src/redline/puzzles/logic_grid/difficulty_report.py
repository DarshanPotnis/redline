"""Difficulty ladder report: generation cost, Z3 effort and clue mix per level.

`make difficulty-report` runs this module and writes reports/difficulty_ladder.md.
"""

import argparse
import logging
import math
import platform
import statistics
import time
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path

import z3

from redline.puzzles.logic_grid.difficulty import RUNS, measure
from redline.puzzles.logic_grid.generate import LADDER, generate
from redline.puzzles.logic_grid.model import CLUE_KINDS

logger = logging.getLogger(__name__)

SEEDS: Mapping[int, Sequence[int]] = {
    level: range(20) if level <= 4 else range(8) for level in sorted(LADDER)
}
OUT = Path("reports/difficulty_ladder.md")


@dataclass(frozen=True)
class LevelStats:
    level: int
    seeds: Sequence[int]
    generation_seconds: list[float]
    clue_counts: list[int]
    conflicts: list[float]  # each puzzle's z3_conflicts_mean
    kind_counts: dict[str, int]


def main(argv: Sequence[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description="Write the logic-grid difficulty ladder report.")
    parser.add_argument("--out", type=Path, default=OUT)
    args = parser.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    report = build_report(SEEDS)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(report)
    logger.info("wrote %s", args.out)


def build_report(seeds: Mapping[int, Sequence[int]]) -> str:
    return render_report(
        [measure_level(level, level_seeds) for level, level_seeds in seeds.items()]
    )


def measure_level(level: int, seeds: Sequence[int]) -> LevelStats:
    stats = LevelStats(level, seeds, [], [], [], dict.fromkeys(CLUE_KINDS, 0))
    started = time.perf_counter()
    for seed in seeds:
        start = time.perf_counter()
        puzzle = generate(level, seed)
        stats.generation_seconds.append(time.perf_counter() - start)
        features = measure(puzzle)
        stats.clue_counts.append(len(puzzle.clues))
        stats.conflicts.append(features["z3_conflicts_mean"])
        for kind in CLUE_KINDS:
            stats.kind_counts[kind] += int(features[f"kind_{kind}"])
    logger.info("level %d: %d puzzles in %.1f s", level, len(seeds), time.perf_counter() - started)
    return stats


def render_report(levels: Sequence[LevelStats]) -> str:
    header = [
        "Level",
        "Grid",
        "Search space",
        "Gen mean",
        "Gen p95",
        "Clues",
        "Conflicts mean",
        "p10",
        "p90",
        *CLUE_KINDS,
    ]
    lines = [
        "# Logic-grid difficulty ladder",
        "",
        f"Generated by `make difficulty-report` with {_seed_summary(levels)}. Conflicts are "
        f"each puzzle's `z3_conflicts_mean` (K={RUNS} uniqueness proofs); the "
        "clue-kind columns are the share of all clues at that level. Generation times come from "
        f"one machine ({platform.system()} {platform.machine()}, Python "
        f"{platform.python_version()}, z3 {z3.get_version_string()}), and Z3 statistics may "
        "differ across platforms.",
        "",
        "| " + " | ".join(header) + " |",
        "|" + "---|" * len(header),
        *(_row(stats) for stats in levels),
        "",
    ]
    return "\n".join(lines)


def _row(stats: LevelStats) -> str:
    houses, attributes = LADDER[stats.level]
    total_clues = sum(stats.kind_counts.values())
    cells = [
        str(stats.level),
        f"{houses}x{attributes}",
        _big(math.prod(math.factorial(houses) for _ in range(attributes))),
        _duration(statistics.fmean(stats.generation_seconds)),
        _duration(_percentile(stats.generation_seconds, 95)),
        f"{statistics.fmean(stats.clue_counts):.1f}",
        f"{statistics.fmean(stats.conflicts):.1f}",
        f"{_percentile(stats.conflicts, 10):.1f}",
        f"{_percentile(stats.conflicts, 90):.1f}",
        *(f"{100 * stats.kind_counts[kind] / total_clues:.1f}%" for kind in CLUE_KINDS),
    ]
    return "| " + " | ".join(cells) + " |"


def _seed_summary(levels: Sequence[LevelStats]) -> str:
    """E.g. "seeds 0-19 at levels 1-4, seeds 0-7 at levels 5-7" (consecutive levels group)."""
    groups: dict[str, list[int]] = {}
    for stats in levels:
        groups.setdefault(f"{min(stats.seeds)}-{max(stats.seeds)}", []).append(stats.level)
    return ", ".join(
        f"seeds {seeds} at level {group[0]}"
        if len(group) == 1
        else f"seeds {seeds} at levels {group[0]}-{group[-1]}"
        for seeds, group in groups.items()
    )


def _percentile(values: Sequence[float], percent: int) -> float:
    if len(values) < 2:
        return values[0]
    return statistics.quantiles(values, n=100, method="inclusive")[percent - 1]


def _duration(seconds: float) -> str:
    return f"{seconds * 1e3:.1f} ms" if seconds < 1 else f"{seconds:.2f} s"


def _big(number: int) -> str:
    return f"{number:,}" if number < 10**9 else f"{number:.2e}".replace("e+", "e")


if __name__ == "__main__":
    main()
